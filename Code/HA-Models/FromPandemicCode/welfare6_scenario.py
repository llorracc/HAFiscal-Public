def _prob_weighted_rec(ctx, eco, changes, duration_workers=1):
    """Run the max_recession_duration MC experiments and average by
    recession-persistence probability. If duration_workers > 1, the
    per-duration loop runs in parallel in forked subprocesses that
    inherit `eco` via copy-on-write (no pickling). Results are
    deterministic and identical to serial execution (validated by
    validate_duration_pool.py).

    PRECONDITION: the caller has just solved `eco` against its current MrkvArray
    (run_recession does eco.solve(); run_recession_AD finishes its AD loop and
    restores the converged solution). BUG-064's sync below relies on it."""
    # BUG-064 -- do not let every forked duration child re-solve the whole economy.
    #
    # run_experiment calls ThisType.solve_if_changed(), which re-solves whenever
    # MrkvArray != MrkvArray_prev. switch_shock_type swaps MrkvArray (6x6 base ->
    # 132x132 recession) and Market.solve() never updates MrkvArray_prev, so on the
    # non-AD path the guard fired on the FIRST task of every fork child: 21 agents,
    # serially, per child. MEASURED 2026-07-30, Baseline recessionCheck, solo box,
    # dw=2: duration loop 3320.6 s -> 208.0 s (16.0x), which is exactly its AD twin's
    # 208.0-238.7 s. Pricing it directly (performing the re-solve in the parent) cost
    # 3329.1 s against an excess of 3112.6 s -- the same quantity.
    #
    # It is NOT the "one extra solve after convergence" sniff test: the discarded
    # re-solve reproduces the policy EXACTLY -- measured move 0.000e+00 at both
    # HS_Only and Baseline, with all result panels agreeing to 4.0e-16 (mean 3e-22),
    # i.e. floating-point summation order. eco.solve() had already solved the agents
    # against this MrkvArray; only the bookkeeping attribute lagged.
    #
    # Synced HERE, not in the callers, so every caller inherits it -- run_recession_AD
    # does the same thing at its own line (kept, now redundant, as documentation of
    # the 2026-07-29 half of this fix, which was applied to the AD path alone).
    # Must run in the PARENT, before the fork, so children inherit the synced state.
    # HAFISCAL_DURATION_RESOLVE=1 restores the old behaviour for A/B work only.
    if os.environ.get("HAFISCAL_DURATION_RESOLVE", "").lower() not in ("1", "on", "true"):
        _sync_mrkv_prev(eco)

    base_dict_agg = deepcopy(ctx["base_dict"])
    Rspell = ctx["Rspell"]
    num_experiment_periods = ctx["num_experiment_periods"]
    max_recession_duration = ctx["max_recession_duration"]
    R_persist = 1.0 - 1.0 / Rspell
    recession_prob = np.array([
        R_persist ** t * (1 - R_persist)
        for t in range(max_recession_duration)
    ])
    recession_prob[-1] = 1.0 - np.sum(recession_prob[:-1])

    # Build per-duration dicts.
    tasks = []
    for dur in range(max_recession_duration):
        d = base_dict_agg.copy()
        d.update(changes)
        rec_path = (
            list(np.arange(1, num_experiment_periods + 1) * 2) + [0] * 20
        )
        rec_path[0 : dur + 1] = (
            np.array(rec_path[0 : dur + 1]) + 1
        ).tolist()
        d["EconomyMrkv_init"] = rec_path
        tasks.append(d)

    # Forking a JAX-loaded process. CPython multiprocessing forks, and JAX warns
    # about it itself ("os.fork() is incompatible with multithreaded code, and JAX
    # is multithreaded, so this will likely lead to a deadlock"): a lock held by a
    # background thread at fork time stays locked forever in the child.
    #
    # BOTH NUMBERS THIS GUARD WAS BUILT ON ARE NOW EXPLAINED BY OTHER CAUSES
    # (2026-07-30), so `auto` re-measures rather than assumes:
    #   * the "15.7x penalty" (JAX arm 3441.5 s vs HARK arm 219.0 s at dw=2,
    #     2026-07-28) was the wasted post-AD re-solve, per the analysis at
    #     run_recession_AD below: HARK's AD loop refreshes MrkvArray_prev through
    #     its own solve() calls and the JAX loop did not, so only the JAX arm paid
    #     it. That is the same defect as BUG-064, on the AD path.
    #   * "the pool does not scale anyway (178.9 s @dw=1 vs 182.6 @dw=2)"
    #     generalised a Reduced-scale NON-AD measurement, which was dominated by
    #     that same per-child re-solve. Re-measured at Baseline on the fixed code
    #     the pool gives 1.70x @dw=2, 3.36x @4, 6.07x @8.
    # So the premise was gone and the guard cost a real ~6x per AD scenario -- but
    # the deadlock hazard is a genuine property of fork(), not an artifact, and it
    # does not announce itself in a wall time, so it was MEASURED rather than
    # reasoned away. R2 probe, Baseline recessionCheck, post-AD economy, JAX
    # imported AND compiled (102 live XLA threads, matching a real AD scenario):
    #
    #   arm      dw=1     dw=8      AggCons
    #   no-jax  361.7s   56.4s    67c2c924f7
    #   jax x3  361.8s   59.1s    67c2c924f7   (54.5 / 62.1 / 60.7)
    #
    # Three repeats at dw=8 because a fork/thread deadlock is a RACE and one clean
    # pass proves little: no hang, 6.12x scaling, and a single AggCons hash across
    # all eight runs. JAX-in-process costs 1.048x at dw=8 -- noise. The duration
    # children never touch JAX (pure HARK/numpy through run_experiment), which is
    # why the classic fork-into-threads hazard does not bite here.
    #
    # Default is therefore 'auto' = keep the pool. HAFISCAL_DURATION_FORK=off
    # restores the forced dw=1 for anyone who hits a hang on other hardware; if
    # that ever happens the right fix is a spawn/forkserver duration pool, not a
    # return to serial.
    _fork_mode = os.environ.get("HAFISCAL_DURATION_FORK", "auto").strip().lower()
    if duration_workers > 1 and 'jax' in sys.modules and _fork_mode == "off":
        print(f"  [_prob_weighted_rec] HAFISCAL_DURATION_FORK=off: forcing "
              f"duration_workers {duration_workers} -> 1 under JAX. Measured cost "
              f"~6.1x on this loop; the default ('auto') keeps the pool.",
              flush=True)
        duration_workers = 1

    t_loop = time()
    if duration_workers <= 1:
        all_results = [eco.run_experiment(**d, Full_Output="ForWelfare")
                       for d in tasks]
    else:
        # Set the module-level eco BEFORE creating the Pool so that
        # forked children inherit the solved-economy reference.
        global _POOL_ECO
        _POOL_ECO = eco
        fork_ctx = multiprocessing.get_context("fork")
        with fork_ctx.Pool(duration_workers) as pool:
            all_results = pool.map(_pool_worker, tasks)
        _POOL_ECO = None
    print(f"  [_prob_weighted_rec] duration loop (n={max_recession_duration}, "
          f"workers={duration_workers}) took {time() - t_loop:.1f}s",
          flush=True)

    avg = {}
    for key in ("cLvl_all_splurge", "AggIncome", "AggCons"):
        avg[key] = np.sum(
            np.array([
                all_results[t][key] * recession_prob[t]
                for t in range(max_recession_duration)
            ]),
            axis=0,
        )
    # Bootstrap-source panel: modal duration (dur=0 is always the mode
    # under the geometric distribution used here). Consumers of the
    # pickle use *_bs fields to recompute MC and MC-L2 welfare on a
    # single duration realization for bootstrap SE estimation.
    avg["cLvl_all_splurge_bs"] = np.asarray(all_results[0]["cLvl_all_splurge"])
    avg["pLvl_all_bs"]         = np.asarray(all_results[0]["pLvl_all"])
    avg["Mrkv_hist_bs"]        = np.asarray(all_results[0]["Mrkv_hist"])
    if "aNrm_all" in all_results[0]:
        avg["aNrm_all_bs"]     = np.asarray(all_results[0]["aNrm_all"])
    # BUG-046 fix (2026-05-16): preserve per-duration cLvl_all_splurge so
    # welfare aggregation can apply u(c) PER DURATION and weight by
    # rec_probs (instead of u(weighted-avg c), which is Jensen-biased by
    # ~−23% for `*_rec` cells with rho=2).
    avg["per_dur_cLvl_all_splurge"] = np.array(
        [all_results[t]["cLvl_all_splurge"] for t in range(max_recession_duration)],
        dtype=np.float64,
    )
    avg["rec_probs"] = recession_prob
    return avg


