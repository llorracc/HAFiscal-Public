"""Standalone per-scenario MC runner for welfare-6.

Runs ONE scenario from the welfare-6 pipeline (as a single subprocess)
and pickles the agent-level consumption/income arrays needed by the
welfare-6 formula. Together with `run_welfare6_parallel.py`, this
replaces the serial loop in `run_hybrid_welfare6.py` with subprocess-
level parallelism.

The economy-build and scenario-dispatch code mirror `run_hybrid_welfare6.py`
exactly so that, when every scenario is run once via this script, the
combined results reproduce the serial pipeline bit-for-bit (validated
by `run_welfare6_scenario_vs_serial.py`). Do not edit this file to
diverge from `run_hybrid_welfare6.py`'s setup without also updating
the validation.

Scenarios:
    base                — no-recession base MC
    Check|UI|TaxCut     — no-recession + policy
    recession           — recession, no AD, no policy (for AD=0 denominators)
    recessionUI|recessionCheck|recessionTaxCut — recession + policy, no AD
    recession_AD        — recession with AD convergence, no policy
    recessionUI_AD|recessionCheck_AD|recessionTaxCut_AD — recession + policy, AD

Usage (single-scenario subprocess):
    python welfare6_scenario.py --scenario recessionUI_AD --baseline
    # writes welfare6_scenario_results/recessionUI_AD.pkl
"""

