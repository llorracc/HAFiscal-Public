def run_one_scenario(ctx, scenario, duration_workers=1, ad_tolerance=None):
    kind, shock_type, changes_key = _DISPATCH[scenario]
    if kind == "base":
        return run_base(ctx)
    changes = ctx[changes_key]
    if kind == "norec":
        return run_norec(ctx, shock_type, changes)
    if kind == "recession":
        return run_recession(ctx, shock_type, changes,
                             duration_workers=duration_workers)
    if kind == "recession_AD":
        return run_recession_AD(ctx, shock_type, changes,
                                duration_workers=duration_workers,
                                ad_tolerance=ad_tolerance)
    raise ValueError(kind)


def main():
    """CLI entry point: run ONE welfare-6 scenario in this process and pickle it.

    Parses --scenario / --parametrization / --seed-offset / parallelism args
    (see the argparse help and the module docstring), builds and solves the
    economy via build_and_solve, always runs the base scenario first (the
    store_baseline prerequisite for AD scenarios), then runs the requested
    scenario and writes <out_dir>/<scenario>.pkl with the agent-level
    consumption/income panels consumed by the welfare-6 formula (payload
    includes the BUG-051 regime stamp).

    Side effects: sets the module global _SOLVE_WORKERS, creates out_dir,
    prints timing/parallelism diagnostics.
    """
    p = argparse.ArgumentParser()
    p.add_argument("--scenario", required=True, choices=SCENARIOS)
    p.add_argument("--parametrization", default="Reduced_Run",
                   help="Parametrization name passed to "
                        "Parameters.return_parameters(). Includes "
                        "Baseline, Reduced_Run, HS_Only, College_Beta_Het, Smoke_Test, and "
                        "the sensitivity names: CRRA1, CRRA3, ADElas, "
                        "Rfree_1005, Rfree_1015, Rspell_4, LowerUBnoB, "
                        "Splurge0 (and their *_PVSame variants). "
                        "Parameters.py rejects unknown names.")
    p.add_argument("--baseline", action="store_true",
                   help="Alias for --parametrization Baseline.")
    p.add_argument("--duration-workers", type=int, default=None,
                   help="Number of forked worker processes for the "
                        "recession-duration loop (only applies to "
                        "recession and recession_AD scenarios). Default: "
                        "auto (budgeted from cpu_count; see "
                        "_auto_standalone_parallel_plan).")
    p.add_argument("--solve-workers", type=int, default=None,
                   help="Number of forked worker processes for the "
                        "per-agent-type solve inside "
                        "AggregateDemandEconomy.solve(). Applies to every "
                        "solve() call (initial, per-scenario, and every "
                        "AD-convergence iteration). Default: auto "
                        "(budgeted from cpu_count).")
    p.add_argument("--ad-tolerance", type=float, default=None,
                   help="Override convergence_tol_solvingAD for the "
                        "AD scenarios in this run. Default: use the value "
                        "from Parameters.py (1E-3; 1E-2 for the reduced "
                        "parametrizations Reduced_Run/Smoke_Test/HS_Only). "
                        "Loosening typically cuts 1-2 iterations.")
    p.add_argument("--agent-count-total", type=int, default=None,
                   help="Override AgentCountTotal from Parameters.py. "
                        "Baseline defaults to 10000; halving to 5000 "
                        "roughly halves per-scenario work. CRN pairing "
                        "in welfare6 tends to be robust to moderate N "
                        "reductions but verify before adopting.")
    p.add_argument("--seed-offset", type=int, default=0,
                   help="Integer offset added to per-agent-type seeds "
                        "(stride 10000) and to IncShkDstn seed (stride 1). "
                        "0 is the canonical run; non-zero values produce "
                        "independent multi-seed batches. CRN within a "
                        "single seed_offset is preserved across all 12 "
                        "scenarios; across offsets, panels are independent.")
    p.add_argument("--out-dir", default=None,
                   help="Directory to write pickle (default: "
                        "welfare6_scenario_results/ inside FromPandemicCode/).")
    args = p.parse_args(_ORIG_ARGV[1:])

    parametrization = "Baseline" if args.baseline else args.parametrization
    out_dir = args.out_dir or os.path.join(HERE, "welfare6_scenario_results")
    os.makedirs(out_dir, exist_ok=True)

    # Companion heuristic for standalone runs (no outer parallel driver).
    # When --solve-workers / --duration-workers are not given, budget
    # inner parallelism from cpu_count(). For a recession scenario:
    # prefer duration-workers (20 durations) first, then solve-workers
    # (21 types) from residual. For non-recession: all budget to
    # solve-workers.
    _is_rec = args.scenario.startswith("recession")
    # Allocation-aware count: under a SLURM cgroup / taskset, os.cpu_count()
    # reports the whole node while the cpuset is the real grant.
    try:
        _ha_mp = os.path.abspath(os.path.join(HERE, ".."))
        if _ha_mp not in sys.path:
            sys.path.insert(0, _ha_mp)
        from machine_profile import effective_cpu_count as _eff_cpu
        _cpu = _eff_cpu()
    except Exception:
        _cpu = os.cpu_count() or 1
    _N_AGENT_TYPES, _N_DURATIONS = 21, 20
    if args.solve_workers is None and args.duration_workers is None:
        if _is_rec:
            # Post-BUG-064 the duration pool SCALES (6.07x at dw=8, re-measured
            # 2026-07-30; see run_welfare6_parallel._auto_parallel_plan and its
            # measurement note). The dw=2 cap this block used to carry was
            # calibrated 2026-07-28 WITH the bug live — the dw>=4 degradation
            # (dw=11 308s; Baseline dw=20 7582s) was each forked child
            # re-solving the economy, not fork COW; test_duration_no_resolve
            # guards the fix. Mirror the battery driver's plan: the solve
            # phase and the duration phase are sequential, so neither splits
            # its core budget with the other.
            _auto_dw = min(8, _N_DURATIONS, _cpu)
            _auto_sw = min(_N_AGENT_TYPES, _cpu)
        else:
            _auto_dw = 1
            _auto_sw = min(_N_AGENT_TYPES, _cpu)
        _solve_w    = _auto_sw
        _duration_w = _auto_dw
        print(f"[auto-parallel] cpu={_cpu} scenario={args.scenario} "
              f"→ solve-workers={_solve_w}  duration-workers={_duration_w}",
              flush=True)
    else:
        _solve_w    = 1 if args.solve_workers    is None else int(args.solve_workers)
        _duration_w = 1 if args.duration_workers is None else int(args.duration_workers)

    # Install the resolved --solve-workers value before build_and_solve,
    # so every AggregateDemandEconomy.solve() call in this process uses
    # the requested parallelism level.
    global _SOLVE_WORKERS
    _SOLVE_WORKERS = max(1, int(_solve_w))

    t0 = time()
    ctx = build_and_solve(parametrization,
                          agent_count_total=args.agent_count_total,
                          seed_offset=args.seed_offset)
    ctx["_seed_offset"] = int(args.seed_offset)
    # If we're running base, store_baseline is called inside run_base.
    # If we're running ANY scenario, the AggEco we built needs a base call
    # before AD scenarios can call store_ADsolution (which depends on
    # stored_solutions being initialized by store_baseline). So always
    # establish the baseline first, then run the requested scenario.
    # R3 base-share (2026-08-02): the only cross-child consumers of the
    # base run are store_baseline's AggCons vector (the AD reference path
    # + the recorded Cratio_hist); the panels serve only the base child's
    # own pkl. So non-base children first try the shared vector (published
    # by any prior base run under the SIM key) and only re-simulate base
    # on a MISS. store_baseline itself snapshots the CURRENT solve state,
    # which run_base does not alter (build_and_solve solved under the base
    # config), and every run_experiment re-seeds its RNG streams — so the
    # skip is exact for all downstream panels (byte-gated at adoption).
    # KEY STATE POINT: the SIM key hashes live agent params, which the base
    # run itself mutates (update_mrkv_array rebuilds objects) — so resolve
    # the key ONCE here, pre-run, and use it for BOTH load and save.
    base_mc = None
    try:
        from solution_cache import (base_aggcons_paths,
                                    load_base_aggcons_cache,
                                    save_base_aggcons_cache)
        _bs_paths = base_aggcons_paths(ctx["AggEco"],
                                       base_dict=ctx["base_dict"],
                                       seed_offset=int(args.seed_offset))
    except Exception:
        _bs_paths = None
    if args.scenario != "base":
        _shared_aggcons = (
            load_base_aggcons_cache(ctx["AggEco"], paths=_bs_paths)
            if _bs_paths is not None else None)
        if _shared_aggcons is not None:
            _ensure_base_solved(ctx["AggEco"])
            ctx["AggEco"].store_baseline(_shared_aggcons)
        else:
            run_base(ctx)
            if _bs_paths is not None:
                save_base_aggcons_cache(ctx["AggEco"],
                                        ctx["AggEco"].base_AggCons,
                                        paths=_bs_paths)
    else:
        base_mc = run_base(ctx)
        if _bs_paths is not None:
            save_base_aggcons_cache(ctx["AggEco"],
                                    ctx["AggEco"].base_AggCons,
                                    paths=_bs_paths)
    t_build = time() - t0

    if args.scenario == "base":
        r = base_mc
    else:
        t0b = time()
        r = run_one_scenario(ctx, args.scenario,
                             duration_workers=_duration_w,
                             ad_tolerance=args.ad_tolerance)
        t_scenario = time() - t0b
        tol_tag = (f"ad_tol={args.ad_tolerance}"
                   if args.ad_tolerance is not None else "ad_tol=default")
        print(f"[{args.scenario}] ran in {t_scenario:.0f}s "
              f"(setup {t_build:.0f}s, duration_workers="
              f"{_duration_w}, solve_workers="
              f"{_SOLVE_WORKERS}, {tol_tag})")

    out_path = os.path.join(out_dir, f"{args.scenario}.pkl")
    # BUG-046: also persist per-duration cLvl_all_splurge for correct
    # welfare aggregation (avoid Jensen bias from u(dur-averaged c)).
    _per_dur_cLvl = r.get("per_dur_cLvl_all_splurge", None)
    _rec_probs = r.get("rec_probs", None)
    payload = {
        "scenario":       args.scenario,
        "parametrization": parametrization,
        "cLvl_all_splurge": np.array(r["cLvl_all_splurge"]),
        "AggCons":          np.array(r["AggCons"]),
        "AggIncome":        np.array(r["AggIncome"]),
        # Bootstrap-source panel. For non-recession scenarios, these
        # are identical to the primary fields. For recession scenarios,
        # cLvl_all_splurge is probability-weighted across 20 duration
        # realizations, but *_bs is a single-duration snapshot (dur=0,
        # the modal duration) used by the control-variate bootstrap.
        # Under CRN with perm_shocks_during_unemployment=True (Baseline
        # parametrization), pLvl_all_bs is invariant across scenarios;
        # it is persisted per-scenario for self-containment.
        "cLvl_all_splurge_bs": np.asarray(r["cLvl_all_splurge_bs"]),
        "pLvl_all_bs":         np.asarray(r["pLvl_all_bs"]),
        "Mrkv_hist_bs":        np.asarray(r["Mrkv_hist_bs"]).astype(np.int32),
        # JAX-MC validation: aNrm_all_bs allows the JAX kernel to use
        # HARK's exact post-warmup asset state as its initial condition.
        # Backward-compatible: existing consumers ignore the key.
        **({"aNrm_all_bs": np.asarray(r["aNrm_all_bs"])}
           if "aNrm_all_bs" in r else {}),
        **({"TranShk_all_bs": np.asarray(r["TranShk_all_bs"])}
           if "TranShk_all_bs" in r else {}),
        **({"PermShk_all_bs": np.asarray(r["PermShk_all_bs"])}
           if "PermShk_all_bs" in r else {}),
        **({"who_dies_all_bs": np.asarray(r["who_dies_all_bs"])}
           if "who_dies_all_bs" in r else {}),
        "act_T":            ctx["act_T"],
        "Rfree":            ctx["Rfree"],
        "CRRA":             ctx["CRRA"],
        "runtime_s":        time() - t0,
        # Matched-pair regime stamp (BUG-051): lets the TM-vs-MC comparison
        # refuse to compare a pickle from a different PermGroFac / UI-encoding /
        # interpretation regime. Mirrors welfare6_hybrid_table.capture_welfare6_regime.
        "regime": {
            "permgrofac_fix": os.environ.get("HAFISCAL_PERMGROFAC_FIX", "1") != "0",
            "ui_state_encoding": os.environ.get("HAFISCAL_UI_STATE_ENCODING", "bug_fix"),
            "interpretation": (os.environ.get("HAFISCAL_INTERPRETATION") or "CDC").upper(),
        },
    }
    if _per_dur_cLvl is not None:
        payload["per_dur_cLvl_all_splurge"] = np.asarray(_per_dur_cLvl)
        payload["rec_probs"] = np.asarray(_rec_probs)
    with open(out_path, "wb") as f:
        pickle.dump(payload, f, protocol=pickle.HIGHEST_PROTOCOL)
    print(f"[{args.scenario}] saved: {out_path} "
          f"({time() - t0:.0f}s wall)")

    # Provenance: standalone runs get a sidecar next to the pickle. Suppressed
    # when spawned by run_welfare6_parallel.py (it emits one aggregate sidecar).
    if os.environ.get("HAFISCAL_PROV_CHILD") != "1":
        _emit_provenance_sidecar(
            [out_dir], label=f"welfare6_scenario-{args.scenario}",
            output_roots=[out_path],
        )
    else:
        # Battery child (sidecar-suppressed): dump the reuse ledger as a
        # dotfile fragment; the driver ingests it into its aggregate sidecar
        # (schema v2, plan 20260803-0900h P1).
        try:
            _ha_frag = os.path.abspath(os.path.join(HERE, ".."))
            if _ha_frag not in sys.path:
                sys.path.insert(0, _ha_frag)
            import provenance as _prov_frag
            _prov_frag.dump_reuse_fragment(
                out_dir, label=f"welfare6_scenario-{args.scenario}")
        except Exception:
            pass


