def _solve_agent_worker(payload):
    """Solve one agent in a child process. Returns (idx, solution).
    `from_solution` is the warm-start seed computed in the parent.
    pre_solve and post_solve are called in the parent, not here, because
    they mutate agent state that must persist after the pool exits.

    Payload shape: (idx, agent, from_solution). The agent is now passed
    through the payload (pickled) rather than via the _POOL_AGENTS global,
    because the spawn context doesn't inherit parent state.

    Honors HAFISCAL_USE_JAX_2B=1: each worker process uses the JAX-native
    iter loop for its own cohort. Combined with multi-process cohort
    parallelism this gives Nx (cores) * 1.66x (2B) = compound speedup."""
    idx, agent, from_solution = payload
    if os.environ.get('HAFISCAL_USE_JAX_2B', '').lower() in ('1', 'on', 'true'):
        _jax_dir = os.path.abspath(os.path.join(
            os.path.dirname(__file__), '..', 'jax_mc_speedup'))
        if _jax_dir not in sys.path:
            sys.path.insert(0, _jax_dir)
        from jax_solver_iterated_drop_in import solve_to_convergence_consumer_solution
        solution = solve_to_convergence_consumer_solution(
            agent, from_solution=from_solution, max_iters=500, tol=1e-7,
            verbose=False)
    else:
        from HARK.core import solve_agent
        from AggFiscalModel import maybe_accel_solution
        # Universal-acceleration router (plan §C14): welfare6's own pool
        # worker was the un-routed third site — welfare6 monkey-patches
        # AggregateDemandEconomy.solve (:325), so the economy-ladder route
        # never runs here and the agent-level override is bypassed by the
        # direct solve_agent call below.
        solution = maybe_accel_solution(agent, from_solution)
        if solution is None:
            solution = solve_agent(agent, False, from_solution=from_solution)
    return idx, solution

